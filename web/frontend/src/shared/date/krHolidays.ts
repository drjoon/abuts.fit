const KR_HOLIDAY_SET = new Set<string>(KR_PUBLIC_HOLIDAY_YMDS);

export function isKrPublicHolidayYmd(ymd?: string | null): boolean {
  const raw = String(ymd || "").trim();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(raw)) return false;
  return KR_HOLIDAY_SET.has(raw);
}
