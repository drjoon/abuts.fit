export function buildAllFdiToothAnatomyDocs() {
  const docs = [];
  for (const spec of TOOTH_CLASS_SPECS) {
    const quadrants = spec.jaw === "upper" ? [1, 2] : [3, 4];
    for (const quadrant of quadrants) {
      const sideLabel = quadrant === 1 || quadrant === 4 ? "우측" : "좌측";
      docs.push({
        toothNumber: `${quadrant}${spec.position}`,
        toothClass: spec.toothClass,
        jaw: spec.jaw,
        quadrant,
        position: spec.position,
        kind: spec.kind,
        koreanName: `${spec.koreanName}(${sideLabel})`,
        crown: spec.crown,
        morphology: spec.morphology,
        abutmentCutback: spec.abutmentCutback,
        surveyMeta: spec.surveyMeta,
      });
    }
  }
  return docs;
}

export async function ensureToothAnatomySeeded({ forceUpdate = false } = {}) {
  const existingCount = await ToothAnatomy.countDocuments();
  const outdatedCount =
    existingCount >= 32
      ? await ToothAnatomy.countDocuments({ "surveyMeta.version": { $ne: TOOTH_ANATOMY_VERSION } })
      : 0;
  if (existingCount >= 32 && outdatedCount === 0 && !forceUpdate) {
    return ToothAnatomy.find({}).sort({ toothNumber: 1 }).lean();
  }
  const docs = buildAllFdiToothAnatomyDocs();
  await ToothAnatomy.bulkWrite(
    docs.map((doc) => ({
      updateOne: {
        filter: { toothNumber: doc.toothNumber },
        update: { $set: doc },
        upsert: true,
      },
    })),
  );
  return ToothAnatomy.find({}).sort({ toothNumber: 1 }).lean();
}
